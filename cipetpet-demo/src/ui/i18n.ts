const dictionaries: Record<UiLang, Record<MessageKey, string>> = { tr, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: UiLang): Translate {
  const d = dictionaries[lang];
  return (key, vars) => {
    const s = d[key] ?? tr[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

export const I18nContext = createContext<{ lang: UiLang; t: Translate }>({ lang: "tr", t: translator("tr") });

export function useT(): Translate {
  return useContext(I18nContext).t;
}

/** "420 ms" below a second, "1.2 s" above */
export function formatMs(t: Translate, ms: number, lang: UiLang): string {
  if (ms < 1000) return t("unit.ms", { n: Math.round(ms) });
  return t("unit.s", { n: (ms / 1000).toLocaleString(lang === "tr" ? "tr-TR" : "en-US", { maximumFractionDigits: 1 }) });
}
